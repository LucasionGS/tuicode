func (a *App) defaultBindings() []config.Binding {
	out := make([]config.Binding, 0, len(defaultKeymap))
	for _, e := range defaultKeymap {
		w, _ := config.ParseWhen(e[2])
		out = append(out, config.Binding{Keys: config.ParseKeys(e[0]), Command: e[1], When: w, WhenSrc: e[2], Source: "default"})
	}
	return out
}
